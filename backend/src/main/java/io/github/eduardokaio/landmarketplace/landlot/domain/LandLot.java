package io.github.eduardokaio.landmarketplace.landlot.domain;

import java.math.BigDecimal;
import java.math.RoundingMode;
import java.time.Instant;
import java.util.UUID;

import io.github.eduardokaio.landmarketplace.shared.geo.GeoConfig;
import jakarta.persistence.Column;
import jakarta.persistence.Embedded;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.Generated;
import org.hibernate.annotations.UpdateTimestamp;
import org.hibernate.generator.EventType;
import org.locationtech.jts.geom.Polygon;

@Entity
@Table(name = "land_lot")
public class LandLot {

	private static final int TITLE_MAX_LENGTH = 120;

	private static final int PRICE_MAX_INTEGER_DIGITS = 13;

	private static final int PRICE_SCALE = 2;

	// Generated by Hibernate on persist. A pre-assigned id would make Spring Data treat the
	// entity as existing and run merge, which costs an extra SELECT.
	@Id
	@GeneratedValue(strategy = GenerationType.UUID)
	private UUID id;

	@Column(nullable = false, length = TITLE_MAX_LENGTH)
	private String title;

	@Column(nullable = false)
	private String description;

	@Column(nullable = false, precision = 15, scale = PRICE_SCALE)
	private BigDecimal price;

	@Embedded
	private Contact contact;

	@Column(nullable = false)
	private Polygon geom;

	// Computed by PostGIS (generated column). Never written by Hibernate, re-read after each write.
	@Generated(event = { EventType.INSERT, EventType.UPDATE })
	@Column(name = "area_m2", insertable = false, updatable = false)
	private Double areaM2;

	@Enumerated(EnumType.STRING)
	@Column(nullable = false, length = 20)
	private LandLotStatus status;

	@CreationTimestamp
	@Column(name = "created_at", nullable = false, updatable = false)
	private Instant createdAt;

	@UpdateTimestamp
	@Column(name = "updated_at", nullable = false)
	private Instant updatedAt;

	// The account id, not a @ManyToOne to the auth entity: the land lot feature only needs to compare
	// ids, and the foreign key in the database already guarantees the account exists. Null for lots
	// created before accounts existed, which nobody can edit.
	@Column(name = "owner_id", updatable = false)
	private UUID ownerId;

	protected LandLot() {
		// required by JPA
	}

	private LandLot(String title, String description, BigDecimal price, Contact contact, Polygon geom,
			UUID ownerId) {
		this.title = title;
		this.description = description;
		this.price = price;
		this.contact = contact;
		this.geom = geom;
		this.ownerId = ownerId;
		this.status = LandLotStatus.AVAILABLE;
	}

	public static LandLot create(String title, String description, BigDecimal price, Contact contact,
			Polygon geom, UUID ownerId) {
		if (ownerId == null) {
			throw new IllegalArgumentException("A new land lot needs an owner");
		}
		return new LandLot(requireTitle(title), requireDescription(description), requirePrice(price),
				requireContact(contact), requireGeometry(geom), ownerId);
	}

	/**
	 * Replaces the listing details. The geometry is not editable: it is the registered shape of the
	 * lot, and changing it would mean checking overlaps again. To fix a shape, delete and create.
	 */
	public void update(String title, String description, BigDecimal price, Contact contact,
			LandLotStatus status) {
		// Everything is checked before anything is assigned, so a rejected update changes nothing
		String validTitle = requireTitle(title);
		String validDescription = requireDescription(description);
		BigDecimal validPrice = requirePrice(price);
		Contact validContact = requireContact(contact);
		if (status == null) {
			throw new InvalidLandLotException("Status is required");
		}
		this.title = validTitle;
		this.description = validDescription;
		this.price = validPrice;
		this.contact = validContact;
		this.status = status;
	}

	/** False for every account when the lot has no owner. */
	public boolean isOwnedBy(UUID accountId) {
		return ownerId != null && ownerId.equals(accountId);
	}

	/**
	 * Price divided by the geodesic area, rounded half up to cents. Only available after the
	 * lot is persisted, because the area is computed by the database.
	 */
	public BigDecimal pricePerSquareMeter() {
		if (areaM2 == null) {
			throw new IllegalStateException("Area is only known after the land lot is persisted");
		}
		return price.divide(BigDecimal.valueOf(areaM2), PRICE_SCALE, RoundingMode.HALF_UP);
	}

	private static String requireTitle(String title) {
		if (title == null || title.isBlank()) {
			throw new InvalidLandLotException("Title is required");
		}
		String stripped = title.strip();
		if (stripped.length() > TITLE_MAX_LENGTH) {
			throw new InvalidLandLotException("Title must have at most " + TITLE_MAX_LENGTH + " characters");
		}
		return stripped;
	}

	private static String requireDescription(String description) {
		if (description == null || description.isBlank()) {
			throw new InvalidLandLotException("Description is required");
		}
		return description.strip();
	}

	private static BigDecimal requirePrice(BigDecimal price) {
		if (price == null || price.signum() <= 0) {
			throw new InvalidLandLotException("Price must be greater than zero");
		}
		BigDecimal normalized = price.stripTrailingZeros();
		if (normalized.scale() > PRICE_SCALE
				|| normalized.precision() - normalized.scale() > PRICE_MAX_INTEGER_DIGITS) {
			throw new InvalidLandLotException("Price must have at most " + PRICE_MAX_INTEGER_DIGITS
					+ " integer digits and " + PRICE_SCALE + " decimals");
		}
		return price.setScale(PRICE_SCALE);
	}

	private static Contact requireContact(Contact contact) {
		if (contact == null) {
			throw new InvalidLandLotException("Contact is required");
		}
		return contact;
	}

	private static Polygon requireGeometry(Polygon geom) {
		if (geom == null) {
			throw new InvalidLandLotException("Geometry is required");
		}
		if (geom.getSRID() != GeoConfig.SRID) {
			throw new InvalidLandLotException("Geometry SRID must be " + GeoConfig.SRID);
		}
		// Same rule as the CHECK (ST_IsValid(geom)) in the database, checked earlier for a clear error
		if (!geom.isValid()) {
			throw new InvalidLandLotException("Geometry must be a valid polygon without self-intersections");
		}
		return geom;
	}

	public UUID getId() {
		return id;
	}

	public String getTitle() {
		return title;
	}

	public String getDescription() {
		return description;
	}

	public BigDecimal getPrice() {
		return price;
	}

	public Contact getContact() {
		return contact;
	}

	public Polygon getGeom() {
		return geom;
	}

	public Double getAreaM2() {
		return areaM2;
	}

	public LandLotStatus getStatus() {
		return status;
	}

	public Instant getCreatedAt() {
		return createdAt;
	}

	public Instant getUpdatedAt() {
		return updatedAt;
	}

	public UUID getOwnerId() {
		return ownerId;
	}

}
